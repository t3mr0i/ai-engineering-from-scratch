/**
 * GitLab publishing adapter for curriculum change sets. It creates one draft
 * branch, commits canonical manifests plus browser compatibility files, and
 * opens a merge request. A change set is published only after GitLab reports
 * that merge request as merged.
 */

class GitLabError extends Error {
  constructor(code, message, status = 400, details) {
    super(message);
    this.code = code;
    this.status = status;
    this.details = details;
  }
}

function jsonSource(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function browserSource(globalName, value) {
  return [
    "// Generated by scripts/build_lrn_manifests.js. Edit the JSON manifest instead.",
    `window.${globalName} = ${JSON.stringify(value, null, 2)};`,
    "",
  ].join("\n");
}

function filesForSnapshot(snapshot) {
  return [
    { filePath: "site/lrn/manifests/catalog.json", content: jsonSource(snapshot.catalog) },
    { filePath: "site/lrn/manifests/curriculum-map.json", content: jsonSource(snapshot.curriculumMap) },
    { filePath: "site/lrn/data.js", content: browserSource("LrnData", snapshot.catalog) },
    { filePath: "site/lrn/curriculum-map.js", content: browserSource("LrnCurriculumMap", snapshot.curriculumMap) },
  ];
}

function lessonCommitMessage(draft) {
  const match = /^phases\/(\d{2})-[^/]+\/(\d{2})-([a-z0-9-]+)$/.exec(draft.path || "");
  if (!match) throw new GitLabError("gitlab.lesson.path", "Ein Lesson-Entwurf besitzt einen ungültigen Pfad.", 422);
  const verb = draft.mode === "create" ? "add" : "update";
  return `feat(phase-${match[1]}/${match[2]}): ${verb} ${match[3]}`.slice(0, 72);
}

function createGitLabPublisher(options = {}) {
  const env = options.env || process.env;
  const fetchFn = options.fetchFn || fetch;
  const baseUrl = String(env.ADMIN_GITLAB_URL || "").replace(/\/$/, "");
  const projectId = env.ADMIN_GITLAB_PROJECT_ID || "";
  const token = env.ADMIN_GITLAB_TOKEN || "";
  const targetBranch = env.ADMIN_GITLAB_TARGET_BRANCH || "main";

  async function request(apiPath, requestOptions = {}, accepted = [200]) {
    if (!baseUrl || !projectId || !token) {
      throw new GitLabError("gitlab.not_configured", "GitLab-Publishing ist für den Curriculum-Admin noch nicht konfiguriert.", 503);
    }
    let response;
    try {
      response = await fetchFn(`${baseUrl}/api/v4/projects/${encodeURIComponent(projectId)}${apiPath}`, {
        ...requestOptions,
        headers: {
          "content-type": "application/json",
          "private-token": token,
          ...(requestOptions.headers || {}),
        },
        signal: AbortSignal.timeout(45_000),
      });
    } catch (_) {
      throw new GitLabError("gitlab.unreachable", "GitLab ist derzeit nicht erreichbar.", 502);
    }
    const text = await response.text();
    let body;
    try { body = text ? JSON.parse(text) : {}; } catch (_) { body = { message: text }; }
    if (!accepted.includes(response.status)) {
      throw new GitLabError("gitlab.request_failed", "GitLab hat den Publishing-Schritt abgelehnt.", 502, {
        upstreamStatus: response.status,
        upstreamMessage: typeof body.message === "string" ? body.message.slice(0, 500) : undefined,
      });
    }
    return body;
  }

  async function branchExists(branch) {
    try {
      await request(`/repository/branches/${encodeURIComponent(branch)}`, { method: "GET" });
      return true;
    } catch (error) {
      if (error instanceof GitLabError && error.details && error.details.upstreamStatus === 404) return false;
      throw error;
    }
  }

  return {
    configured() {
      return Boolean(baseUrl && projectId && token);
    },

    async publish(changeset) {
      const branch = changeset.branch;
      if (!branch || !/^curriculum\/change-[a-z0-9-]+$/.test(branch)) {
        throw new GitLabError("gitlab.branch.invalid", "Der Änderungssatz besitzt keinen gültigen Publishing-Branch.", 422);
      }
      if (await branchExists(branch)) {
        throw new GitLabError("gitlab.branch.exists", "Der Publishing-Branch existiert bereits. Prüfe den vorhandenen Merge Request, bevor du erneut veröffentlichst.", 409);
      }
      await request("/repository/branches", {
        method: "POST",
        body: JSON.stringify({ branch, ref: targetBranch }),
      }, [201]);
      const commit = await request("/repository/commits", {
        method: "POST",
        body: JSON.stringify({
          branch,
          commit_message: `feat(curriculum): publish ${changeset.id}`,
          actions: filesForSnapshot(changeset.snapshot).map((file) => ({
            action: "update",
            file_path: file.filePath,
            content: file.content,
          })),
        }),
      }, [201]);
      const commits = [{ type: "curriculum-manifests", id: commit.id }];
      for (const draft of Object.values(changeset.lessons || {}).sort((left, right) => left.path.localeCompare(right.path))) {
        const existing = new Set(draft.existingFiles || []);
        const lessonCommit = await request("/repository/commits", {
          method: "POST",
          body: JSON.stringify({
            branch,
            commit_message: lessonCommitMessage(draft),
            actions: Object.entries(draft.files || {}).sort(([left], [right]) => left.localeCompare(right)).map(([file, content]) => ({
              action: draft.mode === "create" || !existing.has(file) ? "create" : "update",
              file_path: `${draft.path}/${file}`,
              content,
            })),
          }),
        }, [201]);
        commits.push({ type: "lesson", path: draft.path, id: lessonCommit.id });
      }
      const mergeRequest = await request("/merge_requests", {
        method: "POST",
        body: JSON.stringify({
          source_branch: branch,
          target_branch: targetBranch,
          title: changeset.title,
          description: [
            changeset.description || "Curriculum change created in the admin.",
            "",
            `Change set: ${changeset.id}`,
            `Lesson commits: ${Object.keys(changeset.lessons || {}).length}`,
            "Publishing is completed only after this merge request is merged and CI passes.",
          ].join("\n"),
          remove_source_branch: true,
          squash: false,
        }),
      }, [201]);
      return {
        provider: "gitlab",
        projectId: String(projectId),
        targetBranch,
        branch,
        commitId: commit.id,
        commits,
        state: mergeRequest.state || "opened",
        mergeRequest: {
          iid: mergeRequest.iid,
          url: mergeRequest.web_url,
          title: mergeRequest.title,
        },
      };
    },

    async refresh(publication) {
      if (!publication || !publication.mergeRequest || !publication.mergeRequest.iid) {
        throw new GitLabError("gitlab.publication.missing", "Für den Änderungssatz existiert kein Merge Request.", 404);
      }
      const mergeRequest = await request(`/merge_requests/${encodeURIComponent(publication.mergeRequest.iid)}`, { method: "GET" });
      return {
        ...publication,
        state: mergeRequest.state,
        mergedAt: mergeRequest.merged_at || null,
        mergeRequest: {
          ...publication.mergeRequest,
          url: mergeRequest.web_url || publication.mergeRequest.url,
          title: mergeRequest.title || publication.mergeRequest.title,
        },
      };
    },
  };
}

module.exports = { GitLabError, createGitLabPublisher, filesForSnapshot, browserSource, lessonCommitMessage };
